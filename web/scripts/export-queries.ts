/**
 * Writes db/queries/NN-<id>.sql from the DB Lab catalogue
 * (src/lib/data/mock/lab.ts), so the files and the /admin/db-lab page never
 * disagree. Re-run after changing a query:
 *
 *   npm run db:queries
 *
 * Files that do not match NN-*.sql (rbac-demo.sql, README.md) are left alone.
 */
import { readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { LAB_QUERIES } from "../src/lib/data/mock/lab.ts";

const dir = resolve(dirname(fileURLToPath(import.meta.url)), "../../db/queries");
for (const f of readdirSync(dir)) if (/^\d{2}-.+\.sql$/.test(f)) unlinkSync(resolve(dir, f));

LAB_QUERIES.forEach((q, i) => {
  const name = `${String(i + 1).padStart(2, "0")}-${q.id}.sql`;
  const header = [
    `-- id:       ${q.id}`,
    `-- title:    ${q.title}`,
    `-- concept:  ${q.concept}`,
    `-- rubric:   ${q.rubricItem}`,
    `-- purpose:  ${q.description}`,
    `-- GENERATED by web/scripts/export-queries.ts from src/lib/data/mock/lab.ts. Edit there, then run npm run db:queries.`,
  ].join("\n");
  writeFileSync(resolve(dir, name), `${header}\n\n${q.sql.trim()}\n`);
  console.log(`  ${name}`);
});
console.log(`Wrote ${LAB_QUERIES.length} files to db/queries/.`);

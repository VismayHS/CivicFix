/**
 * Generates the SQL reference data and demo seed from the same deterministic
 * dataset the mock data source uses, so DATA_SOURCE=mock and
 * DATA_SOURCE=postgres show identical data.
 *
 *   node scripts/export-sql.ts        (Node 22.18+ runs TypeScript directly)
 *
 * Writes:
 *   ../db/migrations/002_reference_data.sql
 *   ../db/seed/001_demo_data.sql
 * Timestamps are written relative to now(), so the seed is always "fresh".
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ESCALATION_LEVELS, STATUS_TRANSITIONS } from "../src/lib/constants.ts";
import { buildMockDb } from "../src/lib/data/mock/seed.ts";

const here = dirname(fileURLToPath(import.meta.url));
const NOW = Date.now();
const db = buildMockDb(NOW);

const q = (v: string | null | undefined) => (v === null || v === undefined ? "NULL" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v === null || v === undefined ? "NULL" : String(v));
const b = (v: boolean) => (v ? "TRUE" : "FALSE");
const ts = (ms: number | null) => (ms === null ? "NULL" : `now() - interval '${Math.round((NOW - ms) / 1000)} seconds'`);

function insert(table: string, columns: string[], rows: string[][]) {
  if (!rows.length) return "";
  const chunks: string[] = [];
  for (let i = 0; i < rows.length; i += 200) {
    chunks.push(`INSERT INTO ${table} (${columns.join(", ")}) VALUES\n  ${rows.slice(i, i + 200).map((r) => `(${r.join(", ")})`).join(",\n  ")};`);
  }
  return chunks.join("\n") + "\n";
}

const setval = (table: string, col: string) => `SELECT setval(pg_get_serial_sequence('${table}', '${col}'), (SELECT max(${col}) FROM ${table}));`;

const header = (title: string) => `-- =====================================================================
-- CivicFix · ${title}
-- GENERATED by web/scripts/export-sql.ts. Do not edit by hand: change
-- web/src/lib/data/mock/seed.ts and re-run the script.
-- =====================================================================
`;

// ---------- 002_reference_data.sql ----------
const reference = [
  header("002_reference_data.sql · lookup tables"),
  "-- department: the municipal departments. Each one owns some complaint categories and has its own staff.",
  insert("department", ["department_id", "department_name", "contact_email", "description"], db.departments.map((d) => [n(d.departmentId), q(d.name), q(d.contactEmail), q(d.description)])),
  "-- ward: the city wards. latitude and longitude are the ward centre, used for the map.",
  insert(
    "ward",
    ["ward_id", "ward_number", "ward_name", "zone", "ward_population", "latitude", "longitude"],
    db.wards.map((w) => [n(w.wardId), n(w.wardNumber), q(w.name), q(w.zone), n(w.population), n(w.latitude), n(w.longitude)]),
  ),
  "-- complaint_category: what a citizen can report. department_id decides who handles it; sla_hours is the time\n-- allowed to resolve it (trg_complaint_prepare turns it into the complaint's sla_deadline).",
  insert("complaint_category", ["category_id", "category_name", "department_id", "sla_hours"], db.categories.map((c) => [n(c.categoryId), q(c.name), n(c.departmentId), n(c.slaHours)])),
  "-- status_transition: the status state machine, stored as data. A status change is allowed only if\n-- (from_status, to_status, actor_role) is listed here; the trigger trg_complaint_status_guard checks it.\n-- SYSTEM means automation (the triggers and pg_cron), not a person.",
  insert("status_transition", ["from_status", "to_status", "actor_role"], STATUS_TRANSITIONS.map((t) => [q(t.from), q(t.to), q(t.role)])),
  "-- escalation_policy: who is told, and when, once a complaint passes its deadline.\n-- Level 1 the department head at the breach, level 2 the ward admin after 24 h, level 3 the commissioner after 48 h.",
  insert(
    "escalation_policy",
    ["escalation_level", "target_role", "hours_after_breach", "label"],
    ESCALATION_LEVELS.map((l) => [n(l.level), q(["DEPT_HEAD", "WARD_ADMIN", "COMMISSIONER"][l.level - 1]), n(l.hoursAfterBreach), q(l.label)]),
  ),
  "-- These rows were inserted with explicit ids, so move each id sequence past the highest one.\n-- Without this, the next ordinary INSERT would try to reuse id 1 and fail.",
  [setval("department", "department_id"), setval("ward", "ward_id"), setval("complaint_category", "category_id")].join("\n"),
  "\n-- Record that this migration has run.\nINSERT INTO schema_migrations (version) VALUES ('002_reference_data');\n",
].join("\n");

// ---------- seed/001_demo_data.sql ----------
const userTables = ["app_user", "user_phone", "complaint", "status_history", "escalation", "upvote", "duplicate_match", "notification"];
const seed = [
  header("seed/001_demo_data.sql · demo users and complaints"),
  "-- Every demo account uses the password civicfix123 (bcrypt via pgcrypto).",
  "-- Triggers are disabled while loading so historical rows keep their recorded",
  "-- timestamps and assignments instead of being re-derived.",
  "-- Timestamps are written as now() minus an offset, so the data always looks recent.",
  "-- The whole load is one transaction: it either completes or leaves nothing behind.",
  "BEGIN;",
  "-- DISABLE TRIGGER USER switches off our own triggers (not the constraint checks) for these tables.",
  ...userTables.map((t) => `ALTER TABLE ${t} DISABLE TRIGGER USER;`),
  "-- One bcrypt hash of the demo password (cost 10), computed once and reused for every user.",
  "CREATE TEMP TABLE _demo_pw ON COMMIT DROP AS SELECT crypt('civicfix123', gen_salt('bf', 10)) AS h;",
  "",
  "-- app_user: citizens, staff, ward admins and the commissioner. supervisor_id builds the reporting chain.",
  insert(
    "app_user",
    ["user_id", "name", "email", "password_hash", "role", "department_id", "ward_id", "supervisor_id", "is_active", "created_at"],
    db.users.map((u) => [n(u.userId), q(u.name), q(u.email), "(SELECT h FROM _demo_pw)", q(u.role), n(u.departmentId), n(u.wardId), n(u.supervisorId), b(u.isActive), ts(u.createdAt)]),
  ),
  "-- user_phone: the multivalued Phone_Number attribute of a user, one row per number.",
  insert("user_phone", ["user_id", "phone_number"], db.users.flatMap((u) => u.phones.map((p) => [n(u.userId), q(p)]))),
  "-- complaint: the central table. Keys to category, department, ward, filer and assignee; duplicate_of points at the original.",
  insert(
    "complaint",
    ["complaint_id", "title", "description", "category_id", "department_id", "ward_id", "status", "priority", "address", "latitude", "longitude", "filed_by", "assigned_to", "duplicate_of", "upvote_count", "created_at", "updated_at", "sla_deadline", "resolved_at"],
    db.complaints.map((c) => [
      n(c.complaintId), q(c.title), q(c.description), n(c.categoryId), n(c.departmentId), n(c.wardId), q(c.status), q(c.priority), q(c.address), n(c.latitude), n(c.longitude),
      n(c.filedBy), n(c.assignedTo), n(c.duplicateOf), n(db.upvotes.filter((u) => u.complaintId === c.complaintId).length),
      ts(c.createdAt), ts(c.updatedAt), ts(c.slaDeadline), ts(c.resolvedAt),
    ]),
  ),
  "-- status_history: weak entity of complaint, key (complaint_id, history_no). One row per status change; changed_by NULL = system.",
  insert(
    "status_history",
    ["complaint_id", "history_no", "old_status", "new_status", "changed_by", "remarks", "changed_at"],
    db.history.map((h) => [n(h.complaintId), n(h.historyNo), q(h.oldStatus), q(h.newStatus), n(h.changedBy), q(h.remarks), ts(h.changedAt)]),
  ),
  "-- escalation: weak entity of complaint, key (complaint_id, escalation_level). The chain a late complaint climbed.",
  insert(
    "escalation",
    ["complaint_id", "escalation_level", "escalated_from", "escalated_to", "reason", "escalated_at", "resolved_at"],
    db.escalations.map((e) => [n(e.complaintId), n(e.level), n(e.escalatedFrom), n(e.escalatedTo), q(e.reason), ts(e.escalatedAt), ts(e.resolvedAt)]),
  ),
  "-- upvote: the M:N link between a user and a complaint. complaint.upvote_count already matches these rows.",
  insert("upvote", ["complaint_id", "user_id", "upvoted_at"], db.upvotes.map((u) => [n(u.complaintId), n(u.userId), ts(u.upvotedAt)])),
  "-- duplicate_match: pairs of complaints the vector search judged similar, with the score and the staff review result.",
  insert(
    "duplicate_match",
    ["complaint_id", "matched_complaint_id", "similarity_score", "review_status", "reviewed_by", "detected_at", "reviewed_at"],
    db.matches.map((m) => [n(m.complaintId), n(m.matchedComplaintId), n(m.score), q(m.reviewStatus), n(m.reviewedBy), ts(m.detectedAt), ts(m.reviewedAt)]),
  ),
  "-- notification: messages shown in each user's notification list.",
  insert(
    "notification",
    ["notification_id", "user_id", "complaint_id", "type", "message", "read_status", "sent_at"],
    db.notifications.map((x) => [n(x.notificationId), n(x.userId), n(x.complaintId), q(x.type), q(x.message.slice(0, 255)), b(x.readStatus), ts(x.sentAt)]),
  ),
  "-- Switch the triggers back on, so normal use of the database is validated again.",
  ...userTables.map((t) => `ALTER TABLE ${t} ENABLE TRIGGER USER;`),
  "-- Move the id sequences past the highest loaded id (see 002_reference_data.sql).",
  [setval("app_user", "user_id"), setval("complaint", "complaint_id"), setval("notification", "notification_id")].join("\n"),
  "COMMIT;",
  "",
].join("\n");

writeFileSync(resolve(here, "../../db/migrations/002_reference_data.sql"), reference);
writeFileSync(resolve(here, "../../db/seed/001_demo_data.sql"), seed);
console.log(`Wrote reference data and seed: ${db.users.length} users, ${db.complaints.length} complaints, ${db.history.length} history rows, ${db.escalations.length} escalations, ${db.upvotes.length} upvotes, ${db.matches.length} matches, ${db.notifications.length} notifications.`);

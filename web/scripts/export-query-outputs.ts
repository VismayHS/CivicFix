/**
 * Runs every DB Lab query against the local database (as the commissioner,
 * through civic_admin) and writes docs/database/queries.md: each query's
 * purpose, its SQL and the first rows of its real output. Use it for the
 * report; re-run on a fresh seed before submitting.
 *
 *   npm run docs:queries
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { asAdmin } from "./_db.ts";
import { LAB_QUERIES } from "../src/lib/data/mock/lab.ts";
import { sqlValue } from "../src/lib/sql-value.ts";

const MAX_ROWS = 10;
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../../docs/database/queries.md");

function cell(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (v instanceof Date) return v.toISOString().slice(0, 16).replace("T", " ");
  if (typeof v === "number") return Number.isInteger(v) ? String(v) : v.toFixed(2);
  const s = String(sqlValue(v));
  const n = Number(s);
  const text = /^-?\d+\.\d{3,}$/.test(s) && Number.isFinite(n) ? n.toFixed(2) : s; // numeric columns arrive as strings
  return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

const sections = await asAdmin(async (c) => {
  await c.query("SELECT set_config('app.user_id', '1', true)"); // the commissioner, so fn_* access checks pass
  const parts: string[] = [];
  for (const [i, q] of LAB_QUERIES.entries()) {
    const r = await c.query(q.sql);
    const cols = r.fields.map((f) => f.name);
    const rows = r.rows.slice(0, MAX_ROWS).map((row) => `| ${cols.map((col) => cell(row[col])).join(" | ")} |`);
    parts.push(
      [
        `## ${i + 1}. ${q.title}`,
        "",
        `**Concept:** ${q.concept} · **Rubric:** ${q.rubricItem} · **File:** [\`db/queries/${String(i + 1).padStart(2, "0")}-${q.id}.sql\`](../../db/queries/${String(i + 1).padStart(2, "0")}-${q.id}.sql)`,
        "",
        q.description,
        "",
        "```sql",
        q.sql.trim(),
        "```",
        "",
        `Output (${r.rowCount ?? r.rows.length} row${r.rows.length === 1 ? "" : "s"}${r.rows.length > MAX_ROWS ? `, first ${MAX_ROWS} shown` : ""}):`,
        "",
        `| ${cols.join(" | ")} |`,
        `|${cols.map(() => "---").join("|")}|`,
        ...rows,
      ].join("\n"),
    );
  }
  return parts;
});

const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  out,
  [
    "# Query catalogue with outputs",
    "",
    `**Owner: Vismay.** Rubric item 7 (joins, nested, correlated and recursive queries), the CTE/window/function part of item 8, views (006) and RBAC (item 12). Generated by \`npm run docs:queries\` on ${today} from the seeded database, run as the commissioner through \`civic_admin\`. Seed timestamps are relative to "now", so counts shift slightly between runs.`,
    "",
    "The SQL is the same text the **DB Lab** page (`/admin/db-lab`) runs and the files in [`db/queries/`](../../db/queries/) contain.",
    "",
    "| # | Query | Concept |",
    "|---|---|---|",
    ...LAB_QUERIES.map((q, i) => `| ${i + 1} | ${q.title} | ${q.concept} |`),
    "",
    ...sections.flatMap((s) => [s, ""]),
  ].join("\n"),
);
console.log(`Wrote docs/database/queries.md (${LAB_QUERIES.length} queries).`);
